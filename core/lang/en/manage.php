/*
|--------------------------------------------------------------------------
| The dashboard, in English
|--------------------------------------------------------------------------
|
| ── Why ARABIC is not in a file beside this one ──────────────────────────
|
| It does not need to be. Every call site is `t('key', 'العربية')` — the
| Arabic literal IS the fallback, so Arabic renders correctly with
| `lang/ar/manage.php` completely empty, and it can never go missing because
| a key was forgotten.
|
| That is not laziness, it is the property that made this safe to roll out
| one file at a time: a screen half-extracted still read perfectly in the
| default language while the other forty were still being done. The cost is
| that changing an Arabic word means editing the component rather than a
| translation file — acceptable, because Arabic is the language the people
| who write those components think in.
|
| So this file is the WORK, and `lang/ar/manage.php` stays a deliberate stub.
| `TranslationCoverageTest` enforces both halves.
|
| ── Keys ────────────────────────────────────────────────────────────────
|
| `area.thing`, lower-case, dot-separated:
|
|   common.*      words that appear on MORE THAN ONE screen
|   shell.*       the frame: sidebar, header, layout
|   table.*       the shared DataTable and its controls
|   form.*        shared form primitives
|   <screen>.*    one namespace per screen (orders.*, shipping.*, activity.*)
|
| A key is named for what the text MEANS, never for where it sits, so moving
| a button does not rename its string.
|
| ── `common` earns its place, measured ──────────────────────────────────
|
| The dashboard holds 711 DISTINCT Arabic strings across 42 files (1,027
| counting repeats). 117 of them appear in more than one file — "الرئيسية"
| in 23, "إلغاء" in 10, "المتجر" in 10 — so `common.*` is not tidiness,
| it is roughly 300 occurrences that would otherwise be translated, and
| later re-translated, one screen at a time.
|
| ── One key, ONE Arabic ─────────────────────────────────────────────────
|
| A shared key returns ONE English string, so two screens reaching for it
| with different Arabic is a defect, not a style choice: one of them ends up
| showing English that does not say what its Arabic says, and no test that
| reads a single file can see it. Parallel extraction produced seven of
| these — "مفعّل" against "مفعَّل", the badge "نفد" against the sentence
| "نفد المخزون" — and every one had to be unpicked by hand.
|
| Where Arabic genuinely needs two forms and English only one (a masculine
| provider and a feminine method, both "Active"), that is TWO keys, and the
| narrower one lives on its own screen. `TranslationCoverageTest` fails on
| any key carrying two spellings.
|
| Interpolation is Laravel's own `:name`, so a key can move between a PHP
| `__()` and a React `t()` without the string changing. The React side
| substitutes longest name first, so `:total` survives a `:to` beside it.
|
*/

