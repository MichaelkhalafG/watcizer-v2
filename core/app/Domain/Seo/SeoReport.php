/**
 * THE WEEKLY SEO REPORT (SEO Phase 5 item 2, 2026-11-14) — `seo:weekly-report`, Mondays. One Markdown file per shop and
 * week (config seo.report_dir): the articles (published, scheduled, held, failed, needing an update; the queue in days),
 * the 404s, the sitemap's URL counts, IndexNow's sends, the pages kept out of the index automatically, LIVE vs in-stock
 * counts per article and landing page (information, never an error), and — once their credentials are set — Search
 * Console's clicks, impressions and position per article and per landing page, and Bing's totals. The Phase 1 baseline
 * crawl is a separate Node script; the report names the command that re-runs it.
 */
final class SeoReport
{
    /** Build one shop's report; returns the Markdown. */
    public static function build(int $sf): string
    {
        $name = StorefrontUrls::nameOf($sf) ?? 'shop '.$sf;
        $site = StorefrontUrls::frontend($sf);
        $from = now()->subDays(7);
        $lines = ["# SEO report — {$name}", '', 'Week ending '.now()->setTimezone('Africa/Cairo')->format('Y-m-d').' (Cairo). Generated by `php artisan seo:weekly-report`.', ''];

        // ── articles
        $counts = BlogSafety::counts($sf);
        $published = DB::table('core_blogs')->where('storefront_id', $sf)->where('published_at', '>=', $from)->count();
        $failed = DB::table('core_blogs')->where('storefront_id', $sf)->whereNotNull('publish_error')->count();
        $needs = DB::table('core_blogs')->where('storefront_id', $sf)->whereNotNull('needs_update_reasons')->count();
        $queue = BlogPublisher::queueDays()[$sf] ?? 0.0;
        $lines[] = '## Articles';
        $lines[] = sprintf('- Published this week: %d. Published in all: %d. Scheduled: %d (queue: %.1f days). Held by the gate: %d. Failed to publish: %d. Need an update: %d.',
            $published, $counts['published'] ?? 0, $counts['scheduled'] ?? 0, $queue, $counts['held'] ?? 0, $failed, $needs);
        $lines[] = '- Publishing: '.(BlogPublisher::paused($sf) ? '**PAUSED**' : 'on').'.';
        foreach (array_slice(BlogSafety::alerts($sf), 0, 3) as $a) {
            $lines[] = '- Alert '.substr($a['at'], 0, 10).': '.$a['message'];
        }
        $lines[] = '';

        // ── 404s
        $open = DB::table('seo_not_found')->where('storefront_id', $sf)->whereNull('resolved_at')->count();
        $new = DB::table('seo_not_found')->where('storefront_id', $sf)->where('first_seen_at', '>=', $from)->count();
        $lines[] = '## Pages not found';
        $lines[] = sprintf('- Open: %d (new this week: %d).', $open, $new);
        foreach (DB::table('seo_not_found')->where('storefront_id', $sf)->whereNull('resolved_at')->orderByDesc('hits')->limit(10)->get(['path', 'hits', 'bot_hits']) as $raw) {
            $r = Row::cast($raw);
            $lines[] = sprintf('  - `%s` — %d asks (%d search engines)', Row::str($r, 'path'), Row::int($r, 'hits'), Row::int($r, 'bot_hits'));
        }
        $lines[] = '';

        // ── sitemaps and IndexNow
        $lines[] = '## Sitemaps and IndexNow';
        try {
            $services = new CompatServices(app(StorefrontCache::class), app(InventoryService::class), CompatStorefront::pinned($sf));
            foreach (['en', 'ar'] as $locale) {
                $xml = $services->localeSitemap->urlset($locale) ?? '';
                $lines[] = sprintf('- Sitemap %s: %d URLs.', $locale, substr_count($xml, '<url>'));
            }
        } catch (Throwable $e) {
            $lines[] = '- Sitemaps: could not be counted ('.mb_substr($e->getMessage(), 0, 120).').';
        }
        $sent = DB::table('indexnow_queue')->where('storefront_id', $sf)->where('sent_at', '>=', $from)->selectRaw('status, COUNT(*) AS n')->groupBy('status')->pluck('n', 'status')->all();
        $waiting = DB::table('indexnow_queue')->where('storefront_id', $sf)->whereNull('sent_at')->count();
        $lines[] = '- IndexNow this week: '.($sent === [] ? 'nothing sent' : implode(', ', array_map(fn ($s, $n): string => Coerce::int($n).' answered '.(Coerce::str($s) ?: '?'), array_keys($sent), $sent))).sprintf('; %d waiting.', $waiting);
        $lines[] = '';

        // ── kept out of the index automatically
        $landings = app(LandingPages::class)->all($sf);
        $notIndexable = count(array_filter($landings, fn (array $l): bool => ! $l['indexable']));
        $hidden = DB::table('storefront_product as sp')->join('catalog_products as p', 'p.id', '=', 'sp.product_id')->where('sp.storefront_id', $sf)->where('sp.is_visible', 1)
            ->whereRaw('COALESCE(p.search_override, p.search_class, \'\') = ?', ['hidden'])->count();
        $lines[] = '## Kept out of the index automatically';
        $lines[] = sprintf('- Landing pages without passed copy (noindex): %d of %d. Products kept from search engines: %d.', $notIndexable, count($landings), $hidden);
        $lines[] = '';

        // ── LIVE vs in stock (information)
        $lines[] = '## LIVE and in stock (information, not an error)';
        foreach (array_slice(array_values($landings), 0, 15) as $l) {
            $lines[] = sprintf('- Landing `%s`: %d LIVE.', $l['path'], $l['products']);
        }
        foreach (DB::table('core_blogs')->where('storefront_id', $sf)->where('status', 'published')->orderByDesc('published_at')->limit(15)->get(['id', 'slug']) as $raw) {
            $r = Row::cast($raw);
            $bodies = array_map(fn ($b): string => Coerce::str($b), DB::table('core_blog_translations')->where('blog_id', Row::int($r, 'id'))->pluck('body')->all());
            $blocks = DataBlocks::parse(implode("\n", $bodies));
            if ($blocks === []) {
                continue;
            }
            $total = 0;
            $available = 0;
            foreach (DataBlocks::resolveAll($sf, $blocks) as $b) {
                $total += Coerce::int($b['total'] ?? 0);
                $available += Coerce::int($b['available'] ?? 0);
            }
            $lines[] = sprintf('- Article `%s`: %d LIVE across its blocks, %d in stock.', Row::str($r, 'slug'), $total, $available);
        }
        $lines[] = '';

        // ── search engines
        $lines[] = '## Search engines';
        $end = now()->subDays(3)->format('Y-m-d');
        $start = now()->subDays(9)->format('Y-m-d');
        $gsc = SearchData::gsc($site, $start, $end);
        if ($gsc === null) {
            $lines[] = SearchData::gscConnected() ? '- Search Console: no answer this week (see the log).' : '- Search Console: not connected (GSC_SERVICE_ACCOUNT_JSON is empty).';
        } else {
            $lines[] = sprintf('- Search Console %s → %s: %d clicks, %d impressions, average position %.1f.', $start, $end, $gsc['clicks'], $gsc['impressions'], $gsc['position']);
            $byKind = ['article' => [], 'landing' => []];
            $landingPaths = array_map(fn (array $l): string => $l['path'], $landings);
            foreach ($gsc['pages'] as $p) {
                $path = (string) parse_url($p['page'], PHP_URL_PATH);
                $bare = preg_replace('#^/ar(?=/)#', '', $path) ?? $path;
                if (str_starts_with($bare, '/blog/')) {
                    $byKind['article'][] = $p;
                } elseif (in_array($bare, $landingPaths, true) || preg_match('#^/brand/[^/]+$#', $bare) === 1) {
                    $byKind['landing'][] = $p;
                }
            }
            foreach (['article' => 'Articles', 'landing' => 'Brand and landing pages'] as $k => $label) {
                $lines[] = "- {$label}:";
                foreach (array_slice($byKind[$k], 0, 15) as $p) {
                    $lines[] = sprintf('  - %s — %d clicks, %d impressions, position %.1f', $p['page'], $p['clicks'], $p['impressions'], $p['position']);
                }
            }
            $lines[] = '- The Generative AI performance report has no API yet; read it in Search Console itself.';
        }
        $bing = SearchData::bing($site);
        $lines[] = $bing === null
            ? (SearchData::bingConnected() ? '- Bing: no answer this week (see the log).' : '- Bing Webmaster Tools: not connected (BING_WEBMASTER_API_KEY is empty).')
            : sprintf('- Bing, last 7 days reported: %d clicks, %d impressions. (AI Performance is not in the API; read it in Bing Webmaster Tools.)', $bing['clicks'], $bing['impressions']);
        $lines[] = '';
        $lines[] = '## The baseline crawl';
        $lines[] = '- Re-run it from the repository: `node scripts/seo/crawl.mjs` (read-only; see scripts/seo), then compare with new branding/docs/seo/crawls.';

        return implode("\n", $lines)."\n";
    }

    /** The shop's report address (settings.seo.report_email, the storefront screen), or null. */
    public static function reportEmail(int $storefrontId): ?string
    {
        $settings = json_decode(Coerce::str(DB::table('storefronts')->where('id', $storefrontId)->value('settings')), true);
        $to = trim(Coerce::str(Coerce::arr(Coerce::arr(is_array($settings) ? $settings : [])['seo'] ?? null)['report_email'] ?? ''));

        return $to !== '' && filter_var($to, FILTER_VALIDATE_EMAIL) ? $to : null;
    }

    /**
     * Write every active shop's report; returns the files.
     *
     * @return list<string>
     */
    public static function writeAll(): array
    {
        $dir = Coerce::str(config('seo.report_dir'));
        if (! is_dir($dir)) {
            mkdir($dir, 0775, true);
        }
        $files = [];
        foreach (DB::table('storefronts')->where('is_active', 1)->get(['id', 'code']) as $raw) {
            $r = Row::cast($raw);
            $file = $dir.DIRECTORY_SEPARATOR.Row::str($r, 'code').'-'.now()->format('Y-m-d').'.md';
            $md = self::build(Row::int($r, 'id'));
            file_put_contents($file, $md);
            $files[] = $file;
            // e-mailed too (Michael, 2026-11-14) — to the shop's report address (settings.seo.report_email), when it has one
            $to = self::reportEmail(Row::int($r, 'id'));
            if ($to !== null) {
                try {
                    StorefrontMailer::send(Row::int($r, 'id'), $to, new SeoReportMail(StorefrontUrls::nameOf(Row::int($r, 'id')) ?? Row::str($r, 'code'), $md));
                } catch (Throwable $e) {
                    \Illuminate\Support\Facades\Log::warning('seo report: the e-mail failed', ['storefront' => Row::int($r, 'id'), 'error' => $e->getMessage()]);
                }
            }
        }

        return $files;
    }
}
